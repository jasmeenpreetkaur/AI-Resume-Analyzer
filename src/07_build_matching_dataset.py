def main() -> None:

    logger.info("=" * 70)
    logger.info("AI RESUME ANALYZER - STEP 7 RESUME-JOB MATCHING DATASET")
    logger.info("=" * 70)

    # ------------------------------------------------------------------------
    # Load
    # ------------------------------------------------------------------------

    resumes, jobs = load_datasets()

    # ------------------------------------------------------------------------
    # Detect ESCO mapped skill columns
    # ------------------------------------------------------------------------

    logger.info("")
    logger.info("=" * 70)
    logger.info("Detecting ESCO mapped skill columns")
    logger.info("=" * 70)

    resume_skill_column = detect_esco_skill_column(
        resumes,
        "resume",
    )

    job_skill_column = detect_esco_skill_column(
        jobs,
        "job",
    )

    logger.info(
        "Resume mapped skill column: %s",
        resume_skill_column,
    )

    logger.info(
        "Job mapped skill column: %s",
        job_skill_column,
    )

    # ------------------------------------------------------------------------
    # Build skill sets
    # ------------------------------------------------------------------------

    logger.info("")
    logger.info("=" * 70)
    logger.info("Preparing ESCO skill sets")
    logger.info("=" * 70)

    resume_skill_sets = build_skill_sets(
        resumes,
        resume_skill_column,
        "resume",
    )

    job_skill_sets = build_skill_sets(
        jobs,
        job_skill_column,
        "job",
    )

    # ------------------------------------------------------------------------
    # Shared semantic/lexical/skill candidate generation
    # ------------------------------------------------------------------------
    def resolve_column(frame: pd.DataFrame, aliases: list[str], description: str) -> str:
        mapping = {normalize_column_name(column): column for column in frame.columns}
        for alias in aliases:
            key = normalize_column_name(alias)
            if key in mapping:
                return mapping[key]
        raise ValueError(f"Could not find {description}. Available columns: {list(frame.columns)}")

    resume_id_for_embedding = detect_id_column(resumes, "resume")
    job_id_for_embedding = detect_id_column(jobs, "job")
    resume_text_column = resolve_column(
        resumes, ["resume_text", "text", "resume_str", "cleaned_resume", "resume_content"],
        "resume text column for semantic retrieval",
    )
    job_title_for_embedding = detect_column(
        jobs.columns, ["job_title", "title", "position"], "job title",
    )
    job_description_for_embedding = detect_column(
        jobs.columns, ["job_description", "description", "details"], "job description",
    )
    resume_text_values = [mc.clean_text(value) for value in resumes[resume_text_column]]
    job_text_values = [
        mc.build_job_text(
            row[job_title_for_embedding] if job_title_for_embedding else "",
            row[job_description_for_embedding] if job_description_for_embedding else "",
        )
        for _, row in jobs.iterrows()
    ]

    from sentence_transformers import SentenceTransformer

    logger.info("Loading semantic model for candidate retrieval: %s", mc.SEMANTIC_MODEL_NAME)
    semantic_model = SentenceTransformer(mc.SEMANTIC_MODEL_NAME)

    def encode_text_batch(texts: list[str]) -> np.ndarray:
        return semantic_model.encode(
            texts, batch_size=64, show_progress_bar=False,
            convert_to_numpy=True, normalize_embeddings=True,
        )

    resume_embedding_array = candidate_retrieval.encode_texts_cached(
        resume_text_values, encode=encode_text_batch, model_name=mc.SEMANTIC_MODEL_NAME,
        cache_dir=CACHE_DIR, batch_size=64,
        progress=lambda fraction: logger.info("Resume embedding cache: %.0f%%", fraction * 100),
    )
    job_embedding_array = candidate_retrieval.encode_texts_cached(
        job_text_values, encode=encode_text_batch, model_name=mc.SEMANTIC_MODEL_NAME,
        cache_dir=CACHE_DIR, batch_size=64,
        progress=lambda fraction: logger.info("Job embedding cache: %.0f%%", fraction * 100),
    )
    resume_text_by_id = dict(zip(resumes[resume_id_for_embedding], resume_text_values))
    job_text_by_id = dict(zip(jobs[job_id_for_embedding], job_text_values))
    resume_embeddings_by_id = dict(zip(resumes[resume_id_for_embedding], resume_embedding_array))
    job_embeddings_by_id = dict(zip(jobs[job_id_for_embedding], job_embedding_array))

    resume_stats = summarize_skill_sets(
        resume_skill_sets
    )

    job_stats = summarize_skill_sets(
        job_skill_sets
    )

    logger.info(
        "Resume rows with ESCO skills: %d/%d",
        resume_stats["rows_with_skills"],
        resume_stats["rows"],
    )

    logger.info(
        "Job rows with ESCO skills: %d/%d",
        job_stats["rows_with_skills"],
        job_stats["rows"],
    )

    logger.info(
        "Unique resume ESCO skills: %d",
        resume_stats["unique_skills"],
    )

    logger.info(
        "Unique job ESCO skills: %d",
        job_stats["unique_skills"],
    )

    # ------------------------------------------------------------------------
    # Check overlap BEFORE generating millions of candidates
    # ------------------------------------------------------------------------

    resume_unique_skills = set().union(
        *resume_skill_sets.values()
    ) if resume_skill_sets else set()

    job_unique_skills = set().union(
        *job_skill_sets.values()
    ) if job_skill_sets else set()

    shared_unique_skills = (
        resume_unique_skills
        & job_unique_skills
    )

    logger.info(
        "Shared unique ESCO skills: %d",
        len(shared_unique_skills),
    )

    if not shared_unique_skills:
        logger.warning(
            "No shared ESCO URIs found; proceeding with semantic + lexical candidates "
            "rather than stopping the pipeline."
        )

    # ------------------------------------------------------------------------
    # Generate matches
    # ------------------------------------------------------------------------

    matches, matching_statistics = generate_matches(
        resumes,
        jobs,
        resume_skill_sets,
        job_skill_sets,
        resume_skill_column,
        job_skill_column,
        resume_text_by_id=resume_text_by_id,
        job_text_by_id=job_text_by_id,
        resume_embeddings_by_id=resume_embeddings_by_id,
        job_embeddings_by_id=job_embeddings_by_id,
    )

    matching_df = save_matching_dataset(
        matches
    )

    # ------------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------------

    validate_result(
        matching_df,
        resume_skill_sets,
        job_skill_sets,
    )

    # ------------------------------------------------------------------------
    # Report
    # ------------------------------------------------------------------------

    matching_statistics[
        "shared_unique_esco_skills"
    ] = len(shared_unique_skills)

    report = create_report(
        resumes,
        jobs,
        resume_skill_sets,
        job_skill_sets,
        resume_skill_column,
        job_skill_column,
        matching_statistics,
        matching_df,
    )

    save_report(report)

    # ------------------------------------------------------------------------
    # Final summary
    # ------------------------------------------------------------------------

    logger.info("")
    logger.info("=" * 70)
    logger.info("STEP 7 COMPLETE")
    logger.info("=" * 70)

    logger.info(
        "Possible resume-job pairs: %d",
        len(resumes) * len(jobs),
    )

    logger.info(
        "Shared unique ESCO skills: %d",
        len(shared_unique_skills),
    )

    logger.info(
        "Candidate pairs before limit: %d",
        matching_statistics[
            "candidate_pairs_before_limit"
        ],
    )

    logger.info(
        "Final matching pairs: %d",
        len(matching_df),
    )

    logger.info(
        "Matching dataset: %s",
        OUTPUT_FILE,
    )

    logger.info(
        "Report: %s",
        REPORT_FILE,
    )

    logger.info("=" * 70)


if __name__ == "__main__":
    main()