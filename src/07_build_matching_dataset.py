def create_report(
    resumes: pd.DataFrame,
    jobs: pd.DataFrame,
    resume_skill_sets: Dict[Any, Set[str]],
    job_skill_sets: Dict[Any, Set[str]],
    resume_skill_column: str,
    job_skill_column: str,
    matching_statistics: Dict[str, Any],
    matching_df: pd.DataFrame,
) -> Dict[str, Any]:

    resume_stats = summarize_skill_sets(
        resume_skill_sets
    )

    job_stats = summarize_skill_sets(
        job_skill_sets
    )

    report = {
        "step": "7",
        "description": "Resume-job matching dataset construction",
        "input_files": {
            "resumes": str(RESUME_INPUT),
            "jobs": str(JOB_INPUT),
        },
        "output_file": str(OUTPUT_FILE),
        "configuration": {
            "minimum_shared_skills": MIN_SHARED_SKILLS,
            "maximum_jobs_per_resume": MAX_JOBS_PER_RESUME,
        },
        "input_shapes": {
            "resumes": {
                "rows": int(len(resumes)),
                "columns": int(len(resumes.columns)),
            },
            "jobs": {
                "rows": int(len(jobs)),
                "columns": int(len(jobs.columns)),
            },
        },
        "detected_columns": {
            "resume_skill_column": resume_skill_column,
            "job_skill_column": job_skill_column,
        },
        "resume_skill_statistics": resume_stats,
        "job_skill_statistics": job_stats,
        "matching_statistics": matching_statistics,
        "output_statistics": {
            "rows": int(len(matching_df)),
            "columns": int(len(matching_df.columns)),
        },
    }

    return report


def save_report(report: Dict[str, Any]) -> None:

    REPORT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(
        REPORT_FILE,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            report,
            file,
            indent=2,
            ensure_ascii=False,
        )

    logger.info(
        "Report saved: %s",
        REPORT_FILE,
    )


