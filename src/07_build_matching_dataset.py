def build_skill_sets(
    df: pd.DataFrame,
    skill_column: str,
    entity: str,
) -> Dict[Any, Set[str]]:
    """
    Build:
        entity_id -> set(ESCO skill URIs)
    """

    id_column = detect_id_column(
        df,
        entity,
    )

    result: Dict[Any, Set[str]] = {}

    for _, row in df.iterrows():
        entity_id = row[id_column]

        skill_set = extract_uri_values(
            row[skill_column]
        )

        result[entity_id] = skill_set

    return result


def summarize_skill_sets(
    skill_sets: Dict[Any, Set[str]],
) -> Dict[str, Any]:

    counts = [
        len(skills)
        for skills in skill_sets.values()
    ]

    if not counts:
        return {
            "rows": 0,
            "rows_with_skills": 0,
            "rows_without_skills": 0,
            "average_skills": 0.0,
            "maximum_skills": 0,
            "unique_skills": 0,
        }

    unique_skills = set()

    for skills in skill_sets.values():
        unique_skills.update(skills)

    return {
        "rows": len(counts),
        "rows_with_skills": sum(
            count > 0
            for count in counts
        ),
        "rows_without_skills": sum(
            count == 0
            for count in counts
        ),
        "average_skills": round(
            sum(counts) / len(counts),
            2,
        ),
        "maximum_skills": max(counts),
        "unique_skills": len(unique_skills),
    }


