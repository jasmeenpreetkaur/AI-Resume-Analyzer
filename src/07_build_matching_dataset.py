"""
AI RESUME ANALYZER - STEP 7
Resume-Job Matching Dataset Construction

Purpose
-------
Build a candidate resume-job matching dataset using the ESCO skill mappings
generated by Step 6.5.

This script:
1. Loads Step 6.5 resume/job ESCO mapping outputs.
2. Automatically detects columns containing mapped ESCO skill URIs.
3. Parses skill values safely from CSV/list/string representations.
4. Builds an inverted index from job ESCO skills.
5. Generates resume-job candidate pairs using shared ESCO skills.
6. Calculates matching statistics.
7. Saves the matching dataset and report.

No source dataset is modified.
No embeddings or ML models are used in this step.
"""

