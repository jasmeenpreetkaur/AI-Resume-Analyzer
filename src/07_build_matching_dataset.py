def save_matching_dataset(
    matches: List[Dict[str, Any]],
) -> pd.DataFrame:

    logger.info("")
    logger.info("=" * 70)
    logger.info("Saving matching dataset")
    logger.info("=" * 70)

    output_columns = [
        "resume_id",
        "job_id",
        "resume_category",
        "job_category",
        "job_title",
        "shared_skill_count",
        "resume_skill_count",
        "job_skill_count",
        "jaccard_similarity",
        "resume_skill_coverage",
        "job_skill_coverage",
        "shared_esco_skill_uris",
    ]

    df = pd.DataFrame(
        matches,
        columns=output_columns,
    )

    PROCESSED_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    df.to_csv(
        OUTPUT_FILE,
        index=False,
    )

    logger.info(
        "Saved: %s",
        OUTPUT_FILE,
    )

    logger.info(
        "Matching dataset shape: %s",
        df.shape,
    )

    return df


