def validate_result(
    matching_df: pd.DataFrame,
    resume_skill_sets: Dict[Any, Set[str]],
    job_skill_sets: Dict[Any, Set[str]],
) -> None:

    logger.info("")
    logger.info("=" * 70)
    logger.info("Validating matching dataset")
    logger.info("=" * 70)

    if matching_df.empty:

        logger.warning(
            "No matching pairs were generated."
        )

        total_resume_skills = sum(
            len(skills)
            for skills in resume_skill_sets.values()
        )

        total_job_skills = sum(
            len(skills)
            for skills in job_skill_sets.values()
        )

        resume_unique = set().union(
            *resume_skill_sets.values()
        ) if resume_skill_sets else set()

        job_unique = set().union(
            *job_skill_sets.values()
        ) if job_skill_sets else set()

        overlap = resume_unique.intersection(
            job_unique
        )

        logger.warning(
            "Total resume mapped skills: %d",
            total_resume_skills,
        )

        logger.warning(
            "Total job mapped skills: %d",
            total_job_skills,
        )

        logger.warning(
            "Unique resume ESCO skills: %d",
            len(resume_unique),
        )

        logger.warning(
            "Unique job ESCO skills: %d",
            len(job_unique),
        )

        logger.warning(
            "Shared unique ESCO skills: %d",
            len(overlap),
        )

        if not overlap:
            logger.warning(
                "There is zero ESCO URI overlap between resumes and jobs. "
                "This requires investigation before proceeding to Step 8."
            )

        return

    required_columns = {
        "resume_id",
        "job_id",
        "shared_skill_count",
        "jaccard_similarity",
        "shared_esco_skill_uris",
    }

    missing = required_columns.difference(
        matching_df.columns
    )

    if missing:
        raise ValueError(
            f"Matching dataset is missing required columns: {sorted(missing)}"
        )

    if (
        matching_df["shared_skill_count"] < MIN_SHARED_SKILLS
    ).any():

        raise ValueError(
            "Validation failed: dataset contains pairs "
            "below the minimum shared skill threshold."
        )

    if matching_df["resume_id"].isna().any():
        raise ValueError(
            "Validation failed: missing resume IDs."
        )

    if matching_df["job_id"].isna().any():
        raise ValueError(
            "Validation failed: missing job IDs."
        )

    logger.info(
        "Validation: PASSED"
    )

    logger.info(
        "Generated matching pairs: %d",
        len(matching_df),
    )

    logger.info(
        "Average shared skills per pair: %.2f",
        matching_df["shared_skill_count"].mean(),
    )

    logger.info(
        "Maximum shared skills in one pair: %d",
        matching_df["shared_skill_count"].max(),
    )


