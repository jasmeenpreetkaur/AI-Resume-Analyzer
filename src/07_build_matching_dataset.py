def build_job_inverted_index(
    job_skill_sets: Dict[Any, Set[str]],
) -> Dict[str, Set[Any]]:
    """
    Build:
        ESCO skill URI -> job IDs
    """

    logger.info("")
    logger.info("=" * 70)
    logger.info("Building job inverted index")
    logger.info("=" * 70)

    inverted_index: Dict[str, Set[Any]] = defaultdict(set)

    for job_id, skill_set in job_skill_sets.items():

        for skill_uri in skill_set:
            inverted_index[skill_uri].add(job_id)

    logger.info(
        "Unique ESCO skills appearing in jobs: %d",
        len(inverted_index),
    )

    return inverted_index


