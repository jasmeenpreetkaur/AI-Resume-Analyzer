def normalize_column_name(name: Any) -> str:
    """Normalize a column name for comparison."""
    return re.sub(r"[^a-z0-9]+", "_", str(name).strip().lower()).strip("_")


def detect_column(
    columns: Iterable[str],
    candidates: Iterable[str],
    description: str,
) -> Optional[str]:
    """
    Detect a column using normalized aliases.

    Returns None when no candidate is found.
    """
    normalized = {
        normalize_column_name(column): column
        for column in columns
    }

    for candidate in candidates:
        key = normalize_column_name(candidate)

        if key in normalized:
            return normalized[key]

    logger.warning(
        "Could not automatically detect %s. Available columns: %s",
        description,
        list(columns),
    )

    return None


def detect_id_column(df: pd.DataFrame, entity: str) -> str:
    """Detect resume/job ID column."""
    aliases = {
        "resume": [
            "resume_id",
            "resumeid",
            "id",
        ],
        "job": [
            "job_id",
            "jobid",
            "id",
        ],
    }

    column = detect_column(
        df.columns,
        aliases[entity],
        f"{entity} ID column",
    )

    if column is None:
        raise ValueError(
            f"Could not detect {entity} ID column. "
            f"Available columns: {list(df.columns)}"
        )

    return column


