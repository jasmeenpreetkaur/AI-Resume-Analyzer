def calculate_similarity(
    shared_count: int,
    resume_skill_count: int,
    job_skill_count: int,
) -> float:
    """
    Calculate Jaccard similarity using mapped ESCO skills.
    """

    union_count = (
        resume_skill_count
        + job_skill_count
        - shared_count
    )

    if union_count <= 0:
        return 0.0

    return shared_count / union_count


def calculate_resume_coverage(
    shared_count: int,
    resume_skill_count: int,
) -> float:

    if resume_skill_count <= 0:
        return 0.0

    return shared_count / resume_skill_count


def calculate_job_coverage(
    shared_count: int,
    job_skill_count: int,
) -> float:

    if job_skill_count <= 0:
        return 0.0

    return shared_count / job_skill_count


def generate_matches(
    resumes: pd.DataFrame,
    jobs: pd.DataFrame,
    resume_skill_sets: Dict[Any, Set[str]],
    job_skill_sets: Dict[Any, Set[str]],
    resume_skill_column: str,
    job_skill_column: str,
    *,
    resume_text_by_id: Optional[Dict[Any, str]] = None,
    job_text_by_id: Optional[Dict[Any, str]] = None,
    resume_embeddings_by_id: Optional[Dict[Any, np.ndarray]] = None,
    job_embeddings_by_id: Optional[Dict[Any, np.ndarray]] = None,
) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:

    logger.info("")
    logger.info("=" * 70)
    logger.info("Generating resume-job candidate matches")
    logger.info("=" * 70)

    logger.info(
        "Minimum shared skills: %d",
        MIN_SHARED_SKILLS,
    )

    logger.info(
        "Maximum jobs per resume: %s",
        MAX_JOBS_PER_RESUME
        if MAX_JOBS_PER_RESUME is not None
        else "None",
    )

    resume_id_column = detect_id_column(
        resumes,
        "resume",
    )

    job_id_column = detect_id_column(
        jobs,
        "job",
    )

    resume_category_column = optional_column(
        resumes,
        [
            "category",
            "resume_category",
        ],
    )

    job_category_column = optional_column(
        jobs,
        [
            "category",
            "job_category",
        ],
    )

    job_title_column = optional_column(
        jobs,
        [
            "job_title",
            "title",
        ],
    )

    job_index = build_job_inverted_index(
        job_skill_sets,
    )

    # Helpful lookup tables.
    job_rows = {
        row[job_id_column]: row
        for _, row in jobs.iterrows()
    }

    resume_rows = {
        row[resume_id_column]: row
        for _, row in resumes.iterrows()
    }

    matches: List[Dict[str, Any]] = []

    candidate_pairs_before_limit = 0
    candidate_pairs_after_threshold = 0

    resumes_with_candidates = 0

    # Diagnostic statistics.
    shared_skill_distribution = Counter()
    no_candidate_resumes = []

    resume_items = list(resume_skill_sets.items())
    total_resumes = len(resume_items)
    use_union_retrieval = all(
        value is not None
        for value in (resume_text_by_id, job_text_by_id, resume_embeddings_by_id, job_embeddings_by_id)
    )
    ordered_job_ids = jobs[job_id_column].tolist()
    ordered_job_texts = [
        mc.clean_text((job_text_by_id or {}).get(job_id, ""))
        for job_id in ordered_job_ids
    ]
    ordered_job_skills = [job_skill_sets.get(job_id, set()) for job_id in ordered_job_ids]
    ordered_job_embeddings = None
    if use_union_retrieval:
        try:
            ordered_job_embeddings = np.vstack([
                np.asarray(job_embeddings_by_id[job_id], dtype=np.float32).reshape(-1)
                for job_id in ordered_job_ids
            ])
        except KeyError as exc:
            raise ValueError(f"Missing cached embedding for job ID {exc.args[0]!r}") from exc

    for index, (resume_id, resume_skills) in enumerate(resume_items, start=1):
        candidate_jobs: Dict[Any, Set[str]] = defaultdict(set)
        candidate_metadata: Dict[Any, Dict[str, Any]] = {}

        if use_union_retrieval:
            resume_text = mc.clean_text(resume_text_by_id.get(resume_id, ""))
            resume_embedding = resume_embeddings_by_id.get(resume_id)
            if resume_embedding is None:
                raise ValueError(f"Missing cached embedding for resume ID {resume_id!r}")
            resume_vector = np.asarray(resume_embedding, dtype=np.float32).reshape(-1)
            norm = float(np.linalg.norm(resume_vector))
            if norm > 0:
                resume_vector = resume_vector / norm
            if ordered_job_embeddings.shape[1] != resume_vector.shape[0]:
                raise ValueError("Step 7 resume/job embedding dimensions do not match")
            semantic_cosine = ordered_job_embeddings @ resume_vector
            lexical_scores = np.asarray([
                mc.text_containment(resume_text, text) for text in ordered_job_texts
            ], dtype=np.float32)
            shared_counts = np.asarray([
                len(set(resume_skills) & set(job_skills)) for job_skills in ordered_job_skills
            ], dtype=np.int64)
            jaccards = np.asarray([
                len(set(resume_skills) & set(job_skills)) / len(set(resume_skills) | set(job_skills))
                if (set(resume_skills) | set(job_skills)) else 0.0
                for job_skills in ordered_job_skills
            ], dtype=np.float32)

            selection = candidate_retrieval.select_candidate_indices(
                resume_text=resume_text,
                job_texts=ordered_job_texts,
                resume_skills=resume_skills,
                job_skill_sets=ordered_job_skills,
                semantic_cosine=semantic_cosine,
                lexical_scores=lexical_scores,
                shared_skill_counts=shared_counts,
                skill_jaccard_scores=jaccards,
            )
            for job_position in selection.indices:
                job_id = ordered_job_ids[job_position]
                shared = set(resume_skills) & set(ordered_job_skills[job_position])
                candidate_jobs[job_id].update(shared)
                candidate_metadata[job_id] = {
                    "candidate_retrieval_sources": ",".join(selection.sources[job_position]),
                    "retrieval_semantic_cosine": float(selection.semantic_cosine[job_position]),
                    "retrieval_lexical_overlap": float(selection.lexical_scores[job_position]),
                }
        else:
            # Backwards-compatible helper behaviour for callers that only
            # supply skill sets. The main pipeline always provides all four
            # text/embedding maps and therefore always uses the shared union.
            if resume_skills:
                for skill_uri in resume_skills:
                    for job_id in job_index.get(skill_uri, set()):
                        candidate_jobs[job_id].add(skill_uri)

        if candidate_jobs:
            resumes_with_candidates += 1
        else:
            no_candidate_resumes.append(resume_id)

        candidate_pairs_before_limit += len(candidate_jobs)
        candidate_records = []

        for job_id, shared_skills in sorted(candidate_jobs.items(), key=lambda item: str(item[0])):
            shared_count = len(shared_skills)
            # In union mode a job retrieved semantically or lexically is a
            # valid candidate even when it has no exact ESCO URI overlap.
            if not use_union_retrieval and shared_count < MIN_SHARED_SKILLS:
                continue
            candidate_pairs_after_threshold += 1
            job_skills = job_skill_sets.get(job_id, set())
            similarity = calculate_similarity(shared_count, len(resume_skills), len(job_skills))
            resume_coverage = calculate_resume_coverage(shared_count, len(resume_skills))
            job_coverage = calculate_job_coverage(shared_count, len(job_skills))
            record = {
                "resume_id": resume_id,
                "job_id": job_id,
                "shared_skill_count": shared_count,
                "resume_skill_count": len(resume_skills),
                "job_skill_count": len(job_skills),
                "jaccard_similarity": round(similarity, 6),
                "resume_skill_coverage": round(resume_coverage, 6),
                "job_skill_coverage": round(job_coverage, 6),
                "shared_esco_skill_uris": json.dumps(sorted(shared_skills), ensure_ascii=False),
            }
            record.update(candidate_metadata.get(job_id, {}))
            candidate_records.append(record)
            shared_skill_distribution[shared_count] += 1

        # The shared retriever already applies the per-signal cap. Do not
        # apply a skill-only final cap that would discard semantic/lexical-only
        # candidates. Retain the legacy cap only for fallback callers.
        if not use_union_retrieval and MAX_JOBS_PER_RESUME is not None:
            candidate_records.sort(
                key=lambda record: (record["shared_skill_count"], record["jaccard_similarity"], record["resume_skill_coverage"]),
                reverse=True,
            )
            candidate_records = candidate_records[:MAX_JOBS_PER_RESUME]

        for record in candidate_records:
            job_id = record["job_id"]
            resume_row = resume_rows.get(resume_id)
            job_row = job_rows.get(job_id)
            record["resume_category"] = (
                resume_row[resume_category_column]
                if resume_row is not None and resume_category_column is not None else None
            )
            record["job_category"] = (
                job_row[job_category_column]
                if job_row is not None and job_category_column is not None else None
            )
            record["job_title"] = (
                job_row[job_title_column]
                if job_row is not None and job_title_column is not None else None
            )
            matches.append(record)

        if index % 100 == 0 or index == total_resumes:
            logger.info("Matching progress: %d/%d", index, total_resumes)

    statistics = {
        "candidate_pairs_before_limit": candidate_pairs_before_limit,
        "candidate_pairs_after_threshold": candidate_pairs_after_threshold,
        "final_pairs": len(matches),
        "resumes_with_candidates": resumes_with_candidates,
        "resumes_without_candidates": len(
            no_candidate_resumes
        ),
        "shared_skill_distribution": {
            str(key): value
            for key, value in sorted(
                shared_skill_distribution.items()
            )
        },
        "no_candidate_resume_count": len(no_candidate_resumes),
        "candidate_policy": (
            "semantic_top_k_union_lexical_top_k_union_esco_skill_top_k"
            if use_union_retrieval else "legacy_shared_esco_skill_index"
        ),
        "candidates_per_signal": candidate_retrieval.DEFAULT_CANDIDATES_PER_SIGNAL,
    }

    return matches, statistics


