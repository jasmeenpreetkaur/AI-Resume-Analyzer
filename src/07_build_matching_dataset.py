def is_probably_esco_uri(value: Any) -> bool:
    """
    Check whether a value resembles an ESCO URI.

    ESCO URI examples generally contain:
        http://data.europa.eu/esco/skill/...
        http://data.europa.eu/esco/occupation/...
    """

    if value is None:
        return False

    text = str(value).strip()

    if not text:
        return False

    lowered = text.lower()

    return (
        "data.europa.eu/esco/" in lowered
        or lowered.startswith("http://data.europa.eu/esco/")
        or lowered.startswith("https://data.europa.eu/esco/")
    )


def flatten_values(value: Any) -> List[Any]:
    """
    Convert common CSV representations into a flat list.

    Handles:
    - Python lists
    - tuples
    - sets
    - JSON arrays
    - Python literal lists
    - comma-separated strings
    - pipe-separated strings
    - semicolon-separated strings
    - scalar values
    """

    if value is None:
        return []

    try:
        if pd.isna(value):
            return []
    except Exception:
        pass

    if isinstance(value, (list, tuple, set)):
        result = []

        for item in value:
            result.extend(flatten_values(item))

        return result

    if isinstance(value, dict):
        result = []

        for item in value.values():
            result.extend(flatten_values(item))

        return result

    text = str(value).strip()

    if not text:
        return []

    # Try JSON representation.
    if text.startswith("[") and text.endswith("]"):
        try:
            parsed = json.loads(text)

            if isinstance(parsed, list):
                return flatten_values(parsed)
        except Exception:
            pass

        # Try Python literal representation.
        try:
            parsed = ast.literal_eval(text)

            if isinstance(parsed, (list, tuple, set)):
                return flatten_values(parsed)
        except Exception:
            pass

    # Explicit separators.
    if "||" in text:
        parts = text.split("||")
    elif "|" in text:
        parts = text.split("|")
    elif "\n" in text:
        parts = text.splitlines()
    elif ";" in text:
        parts = text.split(";")
    elif "," in text and not is_probably_esco_uri(text):
        parts = text.split(",")
    else:
        parts = [text]

    return [
        part.strip()
        for part in parts
        if part is not None and str(part).strip()
    ]


def extract_uri_values(value: Any) -> Set[str]:
    """
    Extract ESCO URIs from a value.

    Only values that actually resemble ESCO URIs are retained.
    This prevents ordinary skill labels from being accidentally treated
    as ESCO identifiers.
    """

    values = flatten_values(value)

    uris = set()

    for item in values:
        text = str(item).strip()

        if is_probably_esco_uri(text):
            uris.add(text)

    return uris


def score_esco_column(df: pd.DataFrame, column: str) -> Tuple[float, int]:
    """
    Estimate how strongly a column contains ESCO URIs.

    Returns:
        (coverage, number_of_unique_uris)
    """

    if df.empty:
        return 0.0, 0

    sample_size = min(len(df), 500)

    sample = df[column].head(sample_size)

    total_nonempty = 0
    uri_count = 0
    unique_uris: Set[str] = set()

    for value in sample:
        values = flatten_values(value)

        if values:
            total_nonempty += 1

        for item in values:
            if is_probably_esco_uri(item):
                uri_count += 1
                unique_uris.add(str(item).strip())

    if total_nonempty == 0:
        return 0.0, 0

    coverage = uri_count / max(
        sum(len(flatten_values(value)) for value in sample),
        1,
    )

    return coverage, len(unique_uris)


def detect_esco_skill_column(
    df: pd.DataFrame,
    entity: str,
) -> str:
    """
    Detect the actual column containing mapped ESCO skill URIs.

    Priority:
    1. Explicit URI/mapped aliases.
    2. Columns whose contents strongly resemble ESCO URIs.
    """

    preferred_aliases = [
        "esco_skill_uris",
        "esco_skill_uri",
        "mapped_esco_skills",
        "mapped_esco_skill_uris",
        "esco_mapped_skills",
        "esco_mapped_skill_uris",
        "esco_skills_mapped",
        "mapped_skills",
        "skill_uris",
        "skill_uri",
        "esco_extracted_skills",
        "esco_skill_ids",
    ]

    # First check likely names.
    normalized = {
        normalize_column_name(column): column
        for column in df.columns
    }

    for alias in preferred_aliases:
        normalized_alias = normalize_column_name(alias)

        if normalized_alias in normalized:
            column = normalized[normalized_alias]

            coverage, unique_count = score_esco_column(
                df,
                column,
            )

            if unique_count > 0:
                logger.info(
                    "Detected %s ESCO skill column: %s",
                    entity,
                    column,
                )

                logger.info(
                    "ESCO URI coverage in detected column: %.2f%%",
                    coverage * 100,
                )

                return column

    # Content-based detection.
    candidates = []

    for column in df.columns:
        coverage, unique_count = score_esco_column(
            df,
            column,
        )

        if unique_count > 0:
            candidates.append(
                (
                    coverage,
                    unique_count,
                    column,
                )
            )

    if candidates:
        candidates.sort(
            key=lambda item: (
                item[0],
                item[1],
            ),
            reverse=True,
        )

        best_coverage, best_unique_count, best_column = candidates[0]

        logger.info(
            "Detected %s ESCO skill column by content: %s",
            entity,
            best_column,
        )

        logger.info(
            "ESCO URI coverage: %.2f%% | Unique URIs: %d",
            best_coverage * 100,
            best_unique_count,
        )

        return best_column

    raise ValueError(
        f"Could not detect an ESCO skill URI column in the {entity} "
        f"dataset.\nAvailable columns: {list(df.columns)}"
    )


